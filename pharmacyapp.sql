-- 1. INDEPENDENT TABLES (No Foreign Keys)
CREATE TABLE USER_LOGIN (
    ROLE        VARCHAR2(20),
    PASSWORD    VARCHAR2(20)
);

CREATE TABLE DEPARTMENT (
    DEP_ID      NUMBER PRIMARY KEY NOT NULL,
    DEP_NAME    VARCHAR2(20)
);

CREATE TABLE SUPPLIER (
    SUP_ID      NUMBER PRIMARY KEY NOT NULL,
    SUP_NAME    VARCHAR2(20),
    PHONE       NUMBER,
    ADDRESS     VARCHAR2(20)
);

CREATE TABLE DISTRIBUTOR (
    DISTRIBUTOR_ID NUMBER PRIMARY KEY NOT NULL,
    NAME           VARCHAR2(20),
    PHONE          NUMBER,
    ADDRESS        VARCHAR2(20)
);

CREATE TABLE CUSTOMER (
    CUS_ID        NUMBER PRIMARY KEY NOT NULL,
    CUSTOMER_NAME VARCHAR2(20),
    CUSTOMER_TYPE VARCHAR2(20),
    PHONE         VARCHAR2(20),
    EMAIL         VARCHAR2(20),
    ADDRESS       VARCHAR2(20)
);

CREATE TABLE EXPENSE (
    EXPENSE_ID     NUMBER PRIMARY KEY NOT NULL,
    EXPENSE_TYPE   VARCHAR2(20),
    EXPENSE_AMOUNT NUMBER,
    EXPENSE_DATE   DATE,
    PAYMENT_METHOD VARCHAR2(20),
    DESCRIPTIONS   VARCHAR2(100)
);

CREATE TABLE RAW_MATERIALS (
    MATERIAL_ID     NUMBER PRIMARY KEY NOT NULL,
    MATERIAL_NAME   VARCHAR2(20),
    UNIT            NUMBER,
    MIN_STOCK_LEVEL NUMBER,
    MAX_STOCK_LEVEL NUMBER
);

CREATE TABLE BATCHES (
    BATCH_NO          NUMBER PRIMARY KEY NOT NULL,
    MEDICINE_NAME     VARCHAR2(20),
    QUANTITY_PRODUCED NUMBER,
    RAW_MATERIAL_USED VARCHAR2(20),
    QC_RESULT         VARCHAR2(20),
    BATCH_DATE        DATE,
    EXP_DATE          DATE
);

-- 2. FIRST-LEVEL DEPENDENT TABLES
CREATE TABLE EMPLOYEE (
    EM_ID            NUMBER PRIMARY KEY NOT NULL,
    DEP_ID           NUMBER,
    EM_NAME          VARCHAR2(20),
    EM_GENDER        VARCHAR2(20),
    EM_PHONENO       NUMBER,
    EM_EMAILADDRESS  VARCHAR2(20),
    HIRE_DATE        DATE,
    EM_ROLE          VARCHAR2(20),
    STATUS           VARCHAR2(20),
    HOURS_WORKED     NUMBER,
    SALARY_PER_HOUR  NUMBER,
    TOTAL_PAY        NUMBER,
    TOTAL_SALARY     NUMBER,
    CONSTRAINT FK_EMP_DEP FOREIGN KEY (DEP_ID) REFERENCES DEPARTMENT(DEP_ID)
);

CREATE TABLE MEDICINE (
    MED_ID           NUMBER PRIMARY KEY NOT NULL,
    MED_NAME         VARCHAR2(20),
    FORMULA          VARCHAR2(20),
    COMPANY          VARCHAR2(20),
    DOSAGE           VARCHAR2(20),
    MIN_STOCK_LEVEL  NUMBER,
    MAX_STOCK_LEVEL  NUMBER,
    STATUS           VARCHAR2(20),
    BATCH_NO         NUMBER,
    CONSTRAINT FK_MED_BATCH FOREIGN KEY (BATCH_NO) REFERENCES BATCHES(BATCH_NO)
);

CREATE TABLE PURCHASE (
    PURCHASE_ID   NUMBER PRIMARY KEY NOT NULL,
    SUPPLIER_ID   NUMBER,
    PURCHASE_DATE DATE,
    TOTAL_AMOUNT  NUMBER,
    CONSTRAINT FK_PURCH_SUP FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIER(SUP_ID)
);

CREATE TABLE DISTRIBUTION (
    DISTRIBUTION_ID NUMBER PRIMARY KEY NOT NULL,
    BATCH_ID        NUMBER,
    DISTRIBUTOR_ID  NUMBER,
    QUANTITY        NUMBER,
    DIS_DATE        DATE,
    CONSTRAINT FK_DIST_DISTRIBUTOR FOREIGN KEY (DISTRIBUTOR_ID) REFERENCES DISTRIBUTOR(DISTRIBUTOR_ID),
    CONSTRAINT FK_DIST_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_NO)
);

CREATE TABLE SALES_ORDER (
    SALES_ORDER_ID NUMBER PRIMARY KEY NOT NULL,
    CUSTOMER_ID    NUMBER,
    ORDER_DATE     DATE,
    ORDER_STATUS   VARCHAR2(20),
    TOTAL_AMOUNT   NUMBER,
    CONSTRAINT FK_SO_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUS_ID)
);

CREATE TABLE PRODUCTION (
    PRODUCT_ID            NUMBER PRIMARY KEY NOT NULL,
    P_NAME                VARCHAR2(20),
    P_DATE                DATE,
    QUANTITY              NUMBER,
    RAW_MATERIAL_ID       NUMBER,
    RAW_MATERIAL_QUANTITY NUMBER,
    BATCH_ID              NUMBER,
    STATUS                VARCHAR2(20),
    CONSTRAINT FK_PROD_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_NO),
    CONSTRAINT FK_PROD_MAT FOREIGN KEY (RAW_MATERIAL_ID) REFERENCES RAW_MATERIALS(MATERIAL_ID)
);

-- 3. SECOND-LEVEL DEPENDENT TABLES
CREATE TABLE PURCHASE_ITEMS (
    PURCHASE_ID NUMBER,
    MATERIAL_ID NUMBER,
    QUANTITY    NUMBER,
    UNIT_PRICE  NUMBER,
    CONSTRAINT FK_PI_PURCH FOREIGN KEY (PURCHASE_ID) REFERENCES PURCHASE(PURCHASE_ID),
    CONSTRAINT FK_PI_MAT FOREIGN KEY (MATERIAL_ID) REFERENCES RAW_MATERIALS(MATERIAL_ID)
);

CREATE TABLE QUALITY_CONTROL_TEST (
    TEST_ID     NUMBER PRIMARY KEY NOT NULL,
    BATCH_ID    NUMBER,
    EMPLOYEE_ID NUMBER,
    TEST_DATE   DATE,
    RESULTS     VARCHAR2(20),
    REMARKS     VARCHAR2(20),
    CONSTRAINT FK_QCT_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_NO),
    CONSTRAINT FK_QCT_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EM_ID)
);

CREATE TABLE SALES_ORDER_ITEM (
    SALES_ORDER_ID NUMBER,
    MEDICINE_ID    NUMBER,
    QUANTITY       NUMBER,
    UNIT_PRICE     NUMBER,
    TOTAL_AMOUNT   NUMBER,
    CONSTRAINT FK_SOI_SO FOREIGN KEY (SALES_ORDER_ID) REFERENCES SALES_ORDER(SALES_ORDER_ID),
    CONSTRAINT FK_SOI_MED FOREIGN KEY (MEDICINE_ID) REFERENCES MEDICINE(MED_ID)
);



